import type { AnalysisResult } from '@/types'

/**
 * Export analysis result as Markdown.
 */
export function exportMarkdown(result: AnalysisResult): string {
  const lines: string[] = []
  const { addon, summary } = result

  // Title
  lines.push(`# ${addon.name || 'Add-on 解析レポート'}`)
  lines.push('')

  // Summary
  if (summary.shortDescription) {
    lines.push(`> ${summary.shortDescription}`)
    lines.push('')
  }

  // Pack info
  lines.push('## パック情報')
  lines.push('')
  lines.push(`- **パック構成**: ${addon.packTypes.join(', ') || '不明'}`)
  if (addon.minEngineVersion) lines.push(`- **最小エンジンバージョン**: ${addon.minEngineVersion}`)
  if (addon.dependencies.length > 0) lines.push(`- **依存関係**: ${addon.dependencies.length}件`)
  lines.push('')

  // Content summary
  lines.push('## 追加コンテンツ')
  lines.push('')
  lines.push(`| カテゴリ | 数 |`)
  lines.push(`|---------|-----|`)
  lines.push(`| アイテム | ${result.items.length} |`)
  lines.push(`| ブロック | ${result.blocks.length} |`)
  lines.push(`| モブ | ${result.entities.length} |`)
  lines.push(`| レシピ | ${result.recipes.length} |`)
  lines.push('')

  // Items
  if (result.items.length > 0) {
    lines.push('## アイテム一覧')
    lines.push('')
    for (const item of result.items) {
      const tags = item.tags.length > 0 ? ` [${item.tags.join(', ')}]` : ''
      lines.push(`- \`${item.id}\`${tags}`)
    }
    lines.push('')
  }

  // Blocks
  if (result.blocks.length > 0) {
    lines.push('## ブロック一覧')
    lines.push('')
    for (const block of result.blocks) {
      const tags = block.tags.length > 0 ? ` [${block.tags.join(', ')}]` : ''
      lines.push(`- \`${block.id}\`${tags}`)
    }
    lines.push('')
  }

  // Entities
  if (result.entities.length > 0) {
    lines.push('## モブ一覧')
    lines.push('')
    for (const entity of result.entities) {
      const tags = entity.tags.length > 0 ? ` [${entity.tags.join(', ')}]` : ''
      const hp = entity.health != null ? ` HP:${entity.health}` : ''
      lines.push(`- \`${entity.id}\`${hp}${tags}`)

      // Show loot drops if available
      if (entity.lootTables.length > 0 && result.lootTables.length > 0) {
        for (const ref of entity.lootTables) {
          const refNorm = ref.replace(/\\/g, '/')
          const lt = result.lootTables.find(t => {
            const srcNorm = t.sourcePath.replace(/\\/g, '/')
            return srcNorm.includes(refNorm) || srcNorm.endsWith(refNorm)
          })
          if (!lt) continue
          for (const pool of lt.pools) {
            for (const drop of pool.drops) {
              const pct = (drop.chance * 100)
              const pctStr = pct >= 10 ? `${Math.round(pct)}%` : pct >= 1 ? `${pct.toFixed(1)}%` : `${pct.toFixed(2)}%`
              const count = drop.countMin === drop.countMax ? `${drop.countMin}` : `${drop.countMin}–${drop.countMax}`
              const dropName = drop.title ?? drop.item
              lines.push(`  - Drop: \`${dropName}\` ${pctStr} (×${count})`)
            }
          }
        }
      }
    }
    lines.push('')
  }

  // Recipes
  if (result.recipes.length > 0) {
    lines.push('## レシピ一覧')
    lines.push('')
    for (const recipe of result.recipes) {
      const inputs = recipe.inputs.map(io => io.item).join(' + ')
      const outputs = recipe.outputs.map(io => io.item).join(', ')
      lines.push(`- \`${recipe.id ?? '(unnamed)'}\` (${recipe.recipeType}): ${inputs} → ${outputs}`)
    }
    lines.push('')
  }

  // Warnings
  if (result.warnings.length > 0) {
    lines.push('## 警告')
    lines.push('')
    for (const w of result.warnings) {
      const icon = w.level === 'error' ? '🔴' : w.level === 'warning' ? '🟡' : 'ℹ️'
      lines.push(`- ${icon} ${w.message}${w.path ? ` (\`${w.path}\`)` : ''}`)
    }
    lines.push('')
  }

  lines.push('---')
  lines.push('*Generated by Minecraft Bedrock Add-on Analyzer*')

  return lines.join('\n')
}
